test_that("one affine model supplies the differential and local values", {
  f <- function(v)v[1]^2+2*v[2]^2
  g <- vc_gradient(f,c(1,1))
  a <- f |> vc_linearization(c(1,1),dx=c(.1,.2),gradient=g)
  expect_identical(a$gradient,g)
  expect_equal(a$differential(c(.1,.2)),1,tolerance=1e-7)
  expect_equal(a$model(c(1.1,1.2)),4,tolerance=1e-7)
  expect_equal(a$normal,c(-2,-4,1),tolerance=1e-7)
  expect_equal(sum(a$unit_normal^2),1)
  expect_equal(unname(sum(a$plane_coefficients[1:3]*c(1.1,1.2,a$model(c(1.1,1.2))))+a$plane_coefficients[4]),0,tolerance=1e-7)
  expect_equal(a$comparison$value,c(4.09,3.5225,3.255625),tolerance=1e-10)
  expect_equal(a$comparison$remainder,c(.09,.0225,.005625),tolerance=1e-7)
  expect_equal(a$comparison$remainder[1:2]/a$comparison$remainder[2:3],c(4,4),tolerance=1e-6)
  expect_equal(a$comparison$normalized_remainder[1:2]/a$comparison$normalized_remainder[2:3],c(2,2),tolerance=1e-6)
  expect_true(all(a$comparison$status=="ok"))
  expect_equal(a$differential(c(.1,.2)+c(-.3,.1)),a$differential(c(.1,.2))+a$differential(c(-.3,.1)))
  expect_equal(a$differential(3*c(.1,.2)),3*a$differential(c(.1,.2)))
  no_probes <- vc_linearization(f,c(1,1))
  expect_null(no_probes$comparison)
  expect_equal(no_probes$model(c(1,1)),3)
  affine <- function(v)3*v[1]-2*v[2]+v[3]+5
  b <- vc_linearization(affine,c(1,2,3),dx=rbind(c(.1,.2,-.3),c(-.2,.1,.5)))
  expect_true(all(abs(b$comparison$remainder)<1e-8))
  expect_equal(b$model(c(2,1,4)),affine(c(2,1,4)),tolerance=1e-7)
  single <- vc_linearization(function(v)v[1]^2,1,dx=.2,scales=1)
  old <- vc_differential(function(x)x^2,1,.2)
  expect_equal(single$differential(.2),old$dy,tolerance=1e-8)
  expect_equal(single$comparison$change,old$delta_y,tolerance=1e-8)
})

test_that("named inputs and nonpolynomial comparisons preserve coordinate meaning", {
  f <- function(v)exp(v["x"])*sin(v["y"])
  p <- c(x=0,y=pi/4)
  dx <- c(x=.01,y=-.02)
  a <- vc_linearization(f,p,dx=dx)
  expect_equal(a$differential(dx),sum(rep(sqrt(.5),2)*dx),tolerance=1e-6)
  expect_equal(a$model(p+dx),sqrt(.5)+sum(rep(sqrt(.5),2)*dx),tolerance=1e-6)
  expect_true(all(diff(a$comparison$distance)<0))
  expect_equal(a$comparison$approximation[1],a$model(a$probes[[1]]$endpoint))
  expect_error(a$differential(c(y=.1,x=.2)),"coordinate order")
  expect_error(vc_linearization(f,p,dx=matrix(c(.1,.2),1,dimnames=list(NULL,c("y","x")))),"coordinate order")
})

test_that("stable coordinate partials do not certify a total differential", {
  f <- function(v)if(all(v==0))0 else v[1]^3/sum(v^2)
  a <- vc_linearization(f,c(0,0),dx=c(.1,.1))
  expect_true(a$gradient_reliable)
  expect_equal(a$comparison$normalized_remainder,rep(1/(2*sqrt(2)),3))
  expect_match(a$note,"do not prove total differentiability")
  zero <- vc_linearization(function(v)sum(v),c(1,1),dx=c(0,0))
  expect_true(all(zero$comparison$status=="zero_increment"))
  expect_true(all(is.na(zero$comparison$normalized_remainder)))
  expect_true(all(zero$comparison$change==0))
})

test_that("probe failures remain visible without invalidating a candidate evaluator", {
  boundary <- function(v)sqrt(v[1])+v[2]^2
  a <- vc_linearization(boundary,c(0,1),dx=c(-.1,0),method=c("forward","central"),warn=FALSE)
  expect_true(all(a$comparison$status=="value_not_finite"))
  expect_true(all(is.na(a$comparison$value)))
  expect_true(all(is.finite(a$comparison$approximation)))
  expect_false(a$gradient_reliable)
  collapsed <- vc_linearization(identity,1e16,dx=.1,scales=1)
  expect_identical(collapsed$comparison$status,"collapsed_increment")
  expect_equal(collapsed$differential(.1),.1)
  under <- vc_linearization(identity,1,dx=1e-310,scales=1e-20)
  expect_identical(under$comparison$status,"step_underflow")
  over <- vc_linearization(identity,1,dx=1e308,scales=2)
  expect_identical(over$comparison$status,"step_overflow")
  over <- vc_linearization(identity,1e308,dx=1e308,scales=1)
  expect_identical(over$comparison$status,"endpoint_not_finite")
  for(dx in list(numeric(),1,c(1,Inf),matrix(1,0,2),matrix(1,1,3),1i))
    expect_error(vc_linearization(function(v)sum(v),c(1,2),dx=dx))
  for(scales in list(numeric(),c(1,1),c(.5,1),0,Inf))
    expect_error(vc_linearization(identity,1,scales=scales))
  a <- vc_linearization(function(v)sum(v),c(1,2))
  expect_error(a$differential(1))
  expect_error(a$model(c(Inf,0)))
  expect_error(a$differential(c(1i,0)))
  expect_error(vc_linearization(function(v)sum(v),c(1,2),gradient=vc_gradient(function(v)sum(v),c(2,2))),"same point")
  huge <- vc_linearization(function(v)(v[1]-1e308)+(v[2]-1e308),c(1e308,1e308))
  expect_identical(huge$coefficient_status,"offset_not_finite")
  expect_true(is.na(huge$plane_coefficients[4]))
  expect_equal(huge$model(c(1e308,1e308)),0)
  mixed <- vc_linearization(function(v)1e308*v[1]+1e-308*v[2],c(0,0),warn=FALSE)
  expect_null(mixed$unit_normal)
  expect_match(mixed$normal_status,"underflow")
  expect_equal(mixed$model(c(.1,0)),1e307,tolerance=1e-6)
})

test_that("surface, plane, tangents, normal and probe frames match stored models", {
  skip_if_not_installed("plotly")
  f <- function(v)v[1]^2+2*v[2]^2
  a <- vc_linearization(f,c(1,1),dx=c(.1,.2))
  p <- plotly::plotly_build(vc_plot_linearization(a,f,xlim=c(-1,3),ylim=c(-2,2),n=7,show_normal=TRUE))
  surface <- Filter(function(z)identical(z$name,"Sampled scalar surface"),p$x$data)[[1]]
  plane <- Filter(function(z)identical(z$name,"Candidate affine plane"),p$x$data)[[1]]
  expect_equal(as.numeric(surface$z[2,3]),as.numeric(surface$x[3]^2+2*surface$y[2]^2))
  expect_equal(as.numeric(plane$z[2,3]),a$model(c(plane$x[3],plane$y[2])))
  for(i in 1:2) {
    line <- Filter(function(z)identical(z$name,if(i==1)"Candidate x tangent" else "Candidate y tangent"),p$x$data)[[1]]
    expected <- mapply(function(x,y)a$model(c(x,y)),line$x,line$y)
    expect_equal(as.numeric(line$z),as.numeric(expected))
    cut <- Filter(function(z)identical(z$name,if(i==1)"Actual x section" else "Actual y section"),p$x$data)[[1]]
    expect_equal(as.numeric(cut$z),as.numeric(cut$x)^2+2*as.numeric(cut$y)^2)
  }
  normal <- Filter(function(z)identical(z$name,"Candidate unit normal"),p$x$data)[[1]]
  v <- c(diff(normal$x),diff(normal$y),diff(normal$z))
  expect_equal(sum(v^2),1,tolerance=1e-10)
  expect_equal(sum(v*c(1,0,a$gradient$estimate[1])),0,tolerance=1e-10)
  expect_equal(sum(v*c(0,1,a$gradient$estimate[2])),0,tolerance=1e-10)
  expect_length(p$x$frames,3)
  for(i in seq_along(p$x$frames)) {
    z <- p$x$frames[[i]]$data[[1]]
    expect_equal(as.numeric(z$x),rep(a$probes[[i]]$endpoint[1],2))
    expect_equal(as.numeric(z$y),rep(a$probes[[i]]$endpoint[2],2))
    expect_equal(as.numeric(z$z),c(a$comparison$approximation[i],a$comparison$value[i]))
  }
  p <- plotly::plotly_build(vc_plot_linearization(a,f,animate=FALSE,n=5))
  expect_length(p$x$frames,0)
  single <- vc_linearization(f,c(1,1),dx=c(.1,.2),scales=1)
  expect_length(plotly::plotly_build(vc_plot_linearization(single,f,n=5))$x$frames,0)
  expect_s3_class(vc_plot_linearization(vc_linearization(f,c(1,1)),f,n=5),"plotly")
  expect_error(vc_plot_linearization(a,function(v)f(v)+1),"does not match")
  expect_error(vc_plot_linearization(a,f,plane_alpha=2))
  expect_error(vc_plot_linearization(a,f,show_plane=NA))
  expect_error(vc_plot_linearization(vc_linearization(function(v)sum(v),c(1,2,3)),function(v)sum(v)),"two-dimensional")
})
