})

test_that("system graphics retain zero contours, iteration frames and terminal point", {
  skip_if_not_installed("plotly")
  f <- function(v)c(v[1]^2+v[2]^2-1,v[1]-v[2])
  r <- vc_newton_system(f,c(.8,.2))
  p <- r |> vc_plot_newton_system(f=f,xlim=c(-1,2),ylim=c(-2,1),n=5)
  b <- plotly::plotly_build(p)
  expect_equal(matrix(as.numeric(b$x$data[[1]]$z),5),
    outer(seq(-2,1,length.out=5),seq(-1,2,length.out=5),function(y,x)x^2+y^2-1))
  expect_equal(matrix(as.numeric(b$x$data[[2]]$z),5),
    outer(seq(-2,1,length.out=5),seq(-1,2,length.out=5),function(y,x)x-y))
  expect_equal(b$x$data[[1]]$contours$start,0)
  expect_equal(b$x$data[[1]]$contours$end,0)
  expect_length(b$x$frames,nrow(r$points))
  terminal <- b$x$frames[[length(b$x$frames)]]$data
  expect_equal(b$x$frames[[length(b$x$frames)]]$traces,c(2,3))
  current <- terminal[[2]]
  expect_equal(as.numeric(current$x),r$estimate[1])
  expect_equal(as.numeric(current$y),r$estimate[2])
  root <- vc_newton_system(function(v)v,c(0,0))
  expect_length(plotly::plotly_build(vc_plot_newton_system(root,function(v)v,n=5))$x$frames,0)
  fail <- vc_newton_system(function(v)c(1,1),c(0,0),jacobian=function(v)diag(2),max_backtrack=1)
  rejected <- plotly::plotly_build(vc_plot_newton_system(fail,function(v)c(1,1),n=5,show_rejected=TRUE))
  overlay <- Filter(function(a)grepl("All rejected",a$name),rejected$x$data)[[1]]
  expect_length(overlay$x,2)
  expect_match(as.character(rejected$x$layout$title),"line_search_failed")
  expect_error(vc_plot_newton_system(r,function(v)f(v)+1),"match")
  expect_error(vc_plot_newton_system(r,f,n=1),"n")
  expect_error(vc_plot_newton_system(r,f,animate=NA),"animate")
  expect_error(vc_plot_newton_system(vc_newton_system(function(v)v,c(0,0,0)),function(v)v),"two-dimensional")
})
