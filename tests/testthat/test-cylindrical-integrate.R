test_that("cylindrical refinement retains nested uncertainty", {
 calc <- function(n)vc_cylindrical_integrate(function(v)exp(v[3]),c(0,1),
   function(t)0,function(t)1,function(v)0,function(v)1,method="trapezoid",
   n_outer=2,n_middle=2,n_inner=n,abs_tol=1e-12,rel_tol=1e-12)
 a <- calc(2); b <- calc(8)
 expect_lt(abs(b$estimate-(exp(1)-1)/2),abs(a$estimate-(exp(1)-1)/2))
 expect_false(a$tolerance_met)
 expect_gt(a$slice_error,0)
 expect_equal(a$error_estimate,a$outer_error+a$slice_error)
})
test_that("cylindrical graphics use only stored Cartesian fibers and base", {
 skip_if_not_installed("plotly")
 r <- vc_cylindrical_integrate(sum,c(0,pi/2),function(t)1,function(t)2,
   function(v)-1,function(v)v[2],n_outer=2,n_middle=2,n_inner=2)
 p <- plotly::plotly_build(vc_plot_cylindrical_integral(r))
 a <- p$x$data[[1]]
 expect_equal(as.numeric(a$x)[1:3],c(1,1,NA))
 expect_equal(as.numeric(a$y)[1:3],c(0,0,NA))
 expect_equal(as.numeric(a$z)[1:3],c(-1,1,NA))
 expect_equal(a$type,"scatter3d")
 q <- plotly::plotly_build(vc_plot_cylindrical_integral(r,"projection"))
 d <- r$projection$sections;d <- d[order(d$outer),]
 t <- c(d$outer,rev(d$outer),d$outer[1]); radius <- c(d$upper,rev(d$lower),d$upper[1])
 expect_equal(as.numeric(q$x$data[[1]]$x),radius*cos(t))
 expect_equal(as.numeric(q$x$data[[1]]$y),radius*sin(t))
 expect_error(vc_plot_cylindrical_integral(list()),"Invalid")
 z <- vc_cylindrical_integrate(sum,c(0,0),identity,identity,sum,sum)
 expect_error(vc_plot_cylindrical_integral(z),"No stored")
})
