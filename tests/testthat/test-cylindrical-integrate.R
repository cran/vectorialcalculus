test_that("cylindrical Jacobian and Cartesian field mapping are correct", {
 calc <- function(f,interval=c(0,2*pi),lo=function(t)0,hi=function(t)1,top=function(v)2)
   vc_cylindrical_integrate(f,interval,lo,hi,function(v)0,top,n_outer=8,n_middle=2,n_inner=2)
 a <- calc(function(v)1)
 expect_equal(a$estimate,2*pi)
 expect_true(a$tolerance_met)
 expect_equal(calc(function(v)v[3])$estimate,2*pi)
 expect_equal(calc(function(v)sum(v[1:2]^2))$estimate,pi)
 expect_equal(calc(function(v)v[1],c(0,pi/2))$estimate,2/3,tolerance=2e-6)
 expect_equal(calc(function(v)v[2],c(0,pi/2))$estimate,2/3,tolerance=2e-6)
 expect_equal(calc(function(v)-1,lo=function(t)1,hi=function(t)2)$estimate,-6*pi)
 expect_equal(calc(function(v)1,c(2*pi,0))$estimate,-2*pi)
 expect_equal(calc(function(v)1,top=function(v)1+v[2])$estimate,5*pi/3)
 nested <- vc_triple_integrate(function(v)v[2],c(0,2*pi),function(t)0,function(t)1,
   function(v)0,function(v)2,n_outer=8,n_middle=2,n_inner=2)
 expect_equal(a$outer,nested$outer)
 expect_equal(a$slices,nested$slices)
 expect_equal(a$error_estimate,nested$error_estimate)
 expect_equal(a$type,"cylindrical_integral")
})
