test_that("Taylor plots compare curves and errors on one shared interactive axis", {
  skip_if_not_installed("plotly")
  a <- vc_taylor(exp,0,x=c(-1,0,1))
  p <- plotly::plotly_build(a |> vc_plot_taylor(f=exp,xlim=c(-1,1),n=51))
  expect_s3_class(p,"plotly")
  expect_length(p$x$data,5)
  xs <- as.numeric(p$x$data[[1]]$x)
  expect_equal(as.numeric(p$x$data[[1]]$y), exp(xs))
  expect_equal(as.numeric(p$x$data[[2]]$y), a$polynomial(xs))
  expect_equal(as.numeric(p$x$data[[3]]$x), 0)
  expect_equal(as.numeric(p$x$data[[3]]$y), 1)
  expect_equal(as.numeric(p$x$data[[4]]$y), exp(xs)-a$polynomial(xs))
  expect_equal(as.numeric(p$x$data[[5]]$y), abs(exp(xs)-a$polynomial(xs)))
  expect_true(all(vapply(p$x$data,function(t) identical(t$xaxis,"x"),logical(1))))
  expect_identical(p$x$data[[4]]$yaxis,"y2")
  expect_true(p$x$layout$xaxis$rangeslider$visible)
  expect_match(p$x$data[[2]]$hovertemplate,"%{text}",fixed=TRUE)
  expect_match(p$x$layout$title$text,"not a smoothness proof")
  expect_length(p$x$data[[2]]$text,length(xs))
  expect_true(all(grepl("|x-x0|=",p$x$data[[2]]$text,fixed=TRUE)))
})

test_that("Taylor plot reports unavailable errors and failed diagnostics", {
  skip_if_not_installed("plotly")
  f <- function(x) if (x < 0) NA_real_ else exp(x)
  a <- vc_taylor(f,0,order=1,method="forward")
  p <- plotly::plotly_build(vc_plot_taylor(a,f,xlim=c(-1,1),n=21))
  expect_false(any(p$x$data[[1]]$x < 0))
  expect_false(any(p$x$data[[4]]$x < 0))
  expect_match(p$x$layout$title$text,"11/21",fixed=TRUE)
  expect_false(p$x$data[[1]]$connectgaps)
  expect_true(all(is.finite(p$x$data[[2]]$y)))
  p <- plotly::plotly_build(vc_plot_taylor(vc_taylor(abs,0,warn=FALSE),abs))
  expect_match(p$x$layout$title$text,"FAILED")
})

test_that("Taylor graphical validation and customization are explicit", {
  skip_if_not_installed("plotly")
  a <- vc_taylor(exp,0)
  expect_error(vc_plot_taylor(list(),exp), "valid vc_taylor")
  expect_error(vc_plot_taylor(a,sin),"does not match")
  for (bad in list(c(1,0),c(0,Inf),c(1,2),1i,NA_real_))
    expect_error(vc_plot_taylor(a,exp,xlim=bad),"xlim")
  for (bad in list(1,2.5,Inf,NA_real_,"4"))
    expect_error(vc_plot_taylor(a,exp,n=bad),"integer")
  expect_error(vc_plot_taylor(a,exp,colors="red"),"colors")
  expect_error(vc_plot_taylor(a,exp,title=NA_character_),"labels")
  colors <- c(curve="red",polynomial="blue",error="green",point="black")
  p <- plotly::plotly_build(vc_plot_taylor(a,exp,colors=colors,title="Example",xlab="t",ylab="value"))
  expect_identical(p$x$data[[1]]$line$color,"red")
  expect_match(p$x$layout$title$text,"Example")
  expect_identical(p$x$layout$xaxis$title,"t")
  expect_identical(p$x$layout$yaxis$title,"value")
})

