test_that("the single review script exports all phase widgets and a linked HTML menu", {
  skip_if_not_installed("plotly")
  env <- new.env(parent=globalenv())
  source(system.file("examples","visual-validation.R",package="vectorialcalculus"),local=env)
  directory <- tempfile("vc-review-")
  review <- env$run_visual_validation(display=FALSE,export_dir=directory)
  expect_named(review$files,c("index","secant","tangent","differential","taylor","critical_points","concavity","newton","limit"))
  expect_true(all(file.exists(review$files)))
  menu <- paste(readLines(review$files[["index"]]),collapse="\n")
  for(name in names(review$plots)) {
    expect_match(menu,paste0(name,".html"),fixed=TRUE)
    html <- paste(readLines(review$files[[name]],warn=FALSE),collapse="\n")
    expect_match(html,"plotly",fixed=TRUE)
  }
  # No global files are removed; temporary exports live in R's temp directory.
})
