test_that("signed torsion and curvature agree with analytical spatial curves", {
  r <- function(t)c(cos(t),sin(t),t/2)
  v <- function(t)c(-sin(t),cos(t),.5)
  a <- function(t)c(-cos(t),-sin(t),0)
  j <- function(t)c(sin(t),-cos(t),0)
  exact <- vc_curvature_torsion(r,.3,v,a,j)
  expect_equal(exact$curvature,.8)
  expect_equal(exact$torsion,.4)
  expect_identical(exact$curvature_status,"ok")
  expect_identical(exact$torsion_status,"ok")
  expect_identical(exact$jerk_source,"supplied")
  expect_null(exact$diagnostics)
  numerical <- vc_curvature_torsion(r,.3,h3=.004)
  expect_equal(numerical$curvature,.8,tolerance=1e-6)
  expect_equal(numerical$torsion,.4,tolerance=1e-5)
  expect_equal(numerical$jerk,j(.3),tolerance=1e-5)
  expect_equal(numerical$diagnostics$steps,.004/c(1,2,4))
  expect_identical(numerical$torsion_status,"ok")
  reversed <- vc_curvature_torsion(function(t)r(-t),-.3,
    function(t)-v(-t),function(t)a(-t),function(t)-j(-t))
  expect_equal(reversed$torsion,.4)
  reflected <- vc_curvature_torsion(function(t)c(cos(t),sin(t),-t/2),.3,h3=.004)
  expect_equal(reflected$torsion,-.4,tolerance=1e-5)
  cubic <- vc_curvature_torsion(function(t)c(t,t^2/2,t^3/6),0,h3=2^-8)
  expect_equal(cubic$jerk,c(0,0,1))
  expect_equal(cubic$curvature,1)
  expect_equal(cubic$torsion,1)
  for (scale in c(1e-300,1e300)) {
    scaled <- vc_curvature_torsion(function(t)scale*r(t),.3,
      function(t)scale*v(t),function(t)scale*a(t),function(t)scale*j(t))
    expect_equal(scaled$curvature*scale,.8)
    expect_equal(scaled$torsion*scale,.4)
  }
})

test_that("straight, planar, stationary and unresolved cases are distinct", {
  line <- function(t)c(t,2*t,0)
  straight <- vc_curvature_torsion(line,.5,function(t)c(1,2,0),function(t)c(0,0,0),
    function(t)stop("torsion is unavailable"))
  expect_identical(straight$curvature,0)
  expect_identical(straight$curvature_status,"zero_curvature")
  expect_identical(straight$torsion_status,"unavailable")
  expect_true(is.na(straight$torsion))
  expect_identical(straight$jerk_source,"not_evaluated")
  numerical_line <- vc_curvature_torsion(line,.5)
  expect_identical(numerical_line$curvature,0)
  expect_identical(numerical_line$curvature_status,"unresolved_curvature")
  stopped <- vc_curvature_torsion(function(t)c(t^2,0,0),0,
    function(t)c(2*t,0,0),function(t)c(2,0,0))
  expect_true(is.na(stopped$curvature))
  expect_true(is.na(stopped$torsion))
  expect_identical(stopped$curvature_status,"zero_speed")
  circle <- vc_curvature_torsion(function(t)c(cos(t),sin(t),0),.3,h3=.004)
  expect_equal(circle$curvature,1,tolerance=1e-6)
  expect_identical(circle$torsion,0)
  expect_identical(circle$torsion_status,"ok")
  ambiguous <- vc_curvature_torsion(function(t)c(t,t^2/2,1e14+t^3/6),0,
    function(t)c(1,t,t^2/2),function(t)c(0,1,t))
  expect_equal(ambiguous$curvature,1)
  expect_identical(ambiguous$torsion_status,"unresolved_torsion")
})

test_that("third differences validate inputs and plots use stored results", {
  curve <- function(t)c(t,t^2/2,t^3/6)
  expect_error(vc_curvature_torsion(curve,0,jerk=1),"jerk")
  expect_error(vc_curvature_torsion(curve,0,jerk=function(t)c(1,Inf,0)),"three-vector")
  expect_error(vc_curvature_torsion(curve,0,h3=0),"h3")
  expect_error(vc_curvature_torsion(curve,1,h3=1e-50),"stencil collapsed")
  skip_if_not_installed("plotly")
  samples <- vc_curve_sample(curve,c(-1,1),n=11)
  values <- vc_curvature_torsion(curve,0,h3=2^-8)
  plot <- plotly::plotly_build(vc_plot_curvature_torsion(samples,values,scale=.2))
  expect_match(plot$x$layout$annotations[[1]]$text,"Curvature: 1 / ok")
  expect_match(plot$x$layout$annotations[[1]]$text,"Torsion: 1 / ok")
  expect_length(plot$x$data,5)
  expect_error(vc_plot_curvature_torsion(samples,list()),"Invalid curvature")
})
