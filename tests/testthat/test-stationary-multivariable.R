test_that("stationary graphics preserve contour orientation, candidates and probe playback", {
  skip_if_not_installed("plotly")
  f <- function(v)v[1]^2+2*v[2]^2
  r <- vc_stationary_points(f,c(.1,.2),assume_c2=TRUE,warn=FALSE)
  p <- vc_plot_stationary(r,f,xlim=c(-1,2),ylim=c(-2,1),n=5,max_frames=5)
  b <- plotly::plotly_build(p)
  surface <- b$x$data[[1]]
  expect_equal(matrix(as.numeric(surface$z),5),outer(seq(-2,1,length.out=5),seq(-1,2,length.out=5),function(y,x)x^2+2*y^2))
  candidate <- Filter(function(a)identical(a$name,"Conditional minimum"),b$x$data)[[1]]
  expect_equal(as.numeric(candidate$x),as.numeric(r$points[,1]))
  expect_equal(as.numeric(candidate$y),as.numeric(r$points[,2]))
  expect_length(b$x$frames,5)
  expect_match(as.character(b$x$layout$title),"not iterations")
  expect_length(plotly::plotly_build(vc_plot_stationary(r,f,show_history=FALSE,n=5))$x$frames,0)
  no <- vc_stationary_points(function(v)v[1]+v[2],c(0,0),max_iter=2,warn=FALSE)
  expect_s3_class(vc_plot_stationary(no,function(v)v[1]+v[2],animate=FALSE,n=5),"plotly")
  expect_error(vc_plot_stationary(r,function(v)f(v)+1),"match")
  expect_error(vc_plot_stationary(r,f,run=2),"run")
  expect_error(vc_plot_stationary(r,f,max_frames=1),"max_frames")
  expect_error(vc_plot_stationary(r,f,alpha=2),"alpha")
  expect_error(vc_plot_stationary(r,f,show_history=NA),"show_history")
  expect_error(vc_plot_stationary(r,f,n=1),"n")
})
