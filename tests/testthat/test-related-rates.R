test_that("missing rates obey conditional implicit chain rule", {
 g <- function(v)sum(v^2)-25
 r <- vc_related_rates(g,c(x=4,y=3),c(-1,NA),TRUE,warn=FALSE)
 expect_equal(r$status,"solved")
 expect_equal(r$estimate,4/3,tolerance=1e-7)
 expect_equal(unname(r$rates),c(-1,4/3),tolerance=1e-7)
 expect_lt(abs(r$residual),1e-8)
 expect_equal(r$gradient,vc_gradient(g,c(x=4,y=3),warn=FALSE))
 expect_true(r$denominator>r$denominator_margin)
 expect_true(is.finite(r$rate_indicator))
 expect_equal(vc_related_rates(function(v)v[1]+2*v[2]+3*v[3],c(1,1,-1),c(1,2,NA),TRUE,warn=FALSE)$estimate,-5/3)
 # Explicit time coordinate: x^2-t=0, dt/dt=1.
 expect_equal(vc_related_rates(function(v)v[1]^2-v[2],c(2,4),c(NA,1),TRUE,warn=FALSE)$estimate,.25,tolerance=1e-7)
 expect_equal(vc_related_rates(function(v)v[1]-v[2],c(1,1),c(2,2),TRUE,warn=FALSE)$status,"consistent")
 expect_equal(vc_related_rates(function(v)v[1]-v[2],c(1,1),c(2,3),TRUE,warn=FALSE)$status,"first_order_inconsistent")
})
test_that("feasibility regularity sensitivity and rank gates stay explicit", {
 g <- function(v)v[1]+v[2]
 a <- vc_related_rates(g,c(1,-1),c(1,NA),warn=FALSE)
 expect_equal(a$status,"assumption_required")
 expect_true(is.na(a$rates[2]))
 expect_equal(a$candidate,-1)
 expect_equal(vc_related_rates(g,c(1,1),c(1,NA),TRUE,warn=FALSE)$status,"infeasible")
 expect_equal(vc_related_rates(g,c(0,0),c(NA,NA),TRUE,warn=FALSE)$status,"underdetermined")
 expect_equal(vc_related_rates(function(v)v[1],c(0,1),c(0,NA),TRUE,warn=FALSE)$status,"underdetermined")
 expect_equal(vc_related_rates(function(v)v[1],c(0,1),c(1,NA),TRUE,warn=FALSE)$status,"first_order_inconsistent")
 r <- vc_related_rates(function(v)v[1]+1e-12*v[2],c(0,0),c(1,NA),TRUE,warn=FALSE)
 expect_equal(r$status,"denominator_unresolved")
 expect_true(is.na(r$estimate))
 r <- vc_related_rates(function(v)abs(v[1])+v[2],c(0,0),c(1,NA),TRUE,warn=FALSE)
 expect_equal(r$status,"derivative_unreliable")
 expect_false(r$gradient$reliable)
 # A caller hypothesis is not proven by stable coordinate partials.
 f <- function(v)if(all(v==0))0 else v[1]^3/sum(v^2)
 r <- vc_related_rates(f,c(0,0),c(NA,1),TRUE,warn=FALSE)
 expect_equal(r$status,"solved")
 expect_equal(r$estimate,0)
 expect_match(r$note,"Conditional")
})
test_that("invalid rates names dimensions and field stencils fail", {
 g <- function(v)sum(v)
 for(r in list(c(1),c(1,Inf),c(1,NaN),c(1+1i,NA),matrix(c(1,NA),1)))
   expect_error(vc_related_rates(g,c(0,0),r,warn=FALSE))
 expect_error(vc_related_rates(g,c(x=0,y=0),c(y=NA,x=NA),warn=FALSE),"names")
 expect_error(vc_related_rates(g,c(0,0),c(1,NA),assume_differentiable=NA))
 expect_error(vc_related_rates(g,c(0,0),c(1,NA),denom_tol=0))
 expect_error(vc_related_rates(g,c(0,0),c(1,NA),tol_feasible=Inf))
 expect_error(vc_related_rates(function(v)Inf,c(0,0),c(1,NA)))
 expect_error(vc_related_rates(function(v)if(v[1]<0)stop("domain") else sqrt(v[1])+v[2],c(0,0),c(1,NA)))
 expect_warning(vc_related_rates(g,c(0,0),c(1,NA)),"assumption_required")
})
test_that("related rates geometry uses stored conditional velocity", {
 skip_if_not_installed("plotly")
 g <- function(v)sum(v^2)-25
 r <- vc_related_rates(g,c(4,3),c(-1,NA),TRUE,warn=FALSE)
 p <- plotly::plotly_build(vc_plot_related_rates(r,g,vector_scale=.2))
 tr <- Filter(function(z)identical(z$name,"Conditional velocity"),p$x$data)
 expect_length(tr,1)
 expect_equal(as.numeric(tr[[1]]$x),c(4,3.8))
 expect_equal(as.numeric(tr[[1]]$y),c(3,3+.2*4/3),tolerance=1e-7)
 u <- vc_related_rates(g,c(4,3),c(-1,NA),warn=FALSE)
 q <- plotly::plotly_build(vc_plot_related_rates(u,g))
 expect_false(any(vapply(q$x$data,function(z)identical(z$name,"Conditional velocity"),logical(1))))
 expect_error(vc_plot_related_rates(list(),g),"two-dimensional")
 expect_error(vc_plot_related_rates(r,function(v)sum(v),vector_scale=.2),"match")
})


